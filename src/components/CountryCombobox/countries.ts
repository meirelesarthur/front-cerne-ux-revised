// Função auxiliar para obter um país pelo código
export function getCountryByCode(code: string): CountryItem | undefined {
  return countries.find((c) => c.value === code);
}

// Função auxiliar para obter o nome do país pelo código
export function getCountryName(code: string): string {
  return getCountryByCode(code)?.label || code;
}

// Função auxiliar para obter o emoji do país pelo código
export function getCountryEmoji(code: string): string {
  return getCountryByCode(code)?.emoji || "";
}
